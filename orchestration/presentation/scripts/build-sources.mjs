#!/usr/bin/env node
/*
 * Embeds the real rule / skill files listed in data/rules.js (WFWorkflow.sourceFiles)
 * into data/sources.js so the read-only source viewer works from file:// and static
 * hosting without fetch(). Re-run after editing any listed file:
 *
 *   node orchestration/presentation/scripts/build-sources.mjs
 *
 * tests/provenance.test.mjs fails when data/sources.js is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const here = dirname(fileURLToPath(import.meta.url));
const presentation = resolve(here, '..');
const repo = resolve(presentation, '../..');

export function listSourceFiles() {
  const sandbox = { window: {} };
  vm.createContext(sandbox);
  vm.runInContext(readFileSync(resolve(presentation, 'data/rules.js'), 'utf8'), sandbox);
  return [...sandbox.window.WFWorkflow.sourceFiles];
}

export function renderSources() {
  const files = {};
  for (const path of listSourceFiles()) files[path] = readFileSync(resolve(repo, path), 'utf8');
  return (
    '/* GENERATED by scripts/build-sources.mjs — do not edit. Verbatim copies of repository files\n' +
    ' * for the read-only source viewer. Regenerate after changing any listed file. */\n' +
    `window.WFSources = ${JSON.stringify(files, null, 1)};\n`
  );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = resolve(presentation, 'data/sources.js');
  writeFileSync(out, renderSources());
  console.log(`wrote ${out} (${listSourceFiles().length} files)`);
}
